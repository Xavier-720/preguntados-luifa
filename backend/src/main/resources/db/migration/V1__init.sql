CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL,
    color VARCHAR(20) NOT NULL,
    display_order INTEGER NOT NULL,
    CONSTRAINT uk_categories_name UNIQUE (name)
);

CREATE TABLE questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL,
    prompt VARCHAR(500) NOT NULL,
    fact VARCHAR(500) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_questions_category FOREIGN KEY (category_id) REFERENCES categories (id) ON DELETE CASCADE
);

CREATE INDEX idx_questions_category ON questions (category_id);

CREATE TABLE question_options (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id BIGINT NOT NULL,
    label VARCHAR(200) NOT NULL,
    correct BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_options_question FOREIGN KEY (question_id) REFERENCES questions (id) ON DELETE CASCADE
);

CREATE INDEX idx_options_question ON question_options (question_id);

CREATE TABLE app_settings (
    id INTEGER PRIMARY KEY,
    total_rounds INTEGER NOT NULL,
    required_correct INTEGER NOT NULL,
    question_seconds INTEGER NOT NULL,
    stock_hats INTEGER NOT NULL,
    stock_cups INTEGER NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

