CREATE TABLE game_sessions (
    id UUID PRIMARY KEY,
    status VARCHAR(20) NOT NULL,
    total_rounds INTEGER NOT NULL,
    required_correct INTEGER NOT NULL,
    question_seconds INTEGER NOT NULL,
    correct_answers INTEGER NOT NULL DEFAULT 0,
    rounds_played INTEGER NOT NULL DEFAULT 0,
    prize VARCHAR(20),
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at TIMESTAMP WITH TIME ZONE,
    prize_awarded_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_sessions_started ON game_sessions (started_at);

CREATE TABLE game_rounds (
    id UUID PRIMARY KEY,
    game_session_id UUID NOT NULL,
    round_number INTEGER NOT NULL,
    category_id BIGINT NOT NULL,
    question_id BIGINT NOT NULL,
    answered BOOLEAN NOT NULL DEFAULT FALSE,
    selected_option_id BIGINT,
    correct BOOLEAN,
    timed_out BOOLEAN NOT NULL DEFAULT FALSE,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    answered_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_rounds_session FOREIGN KEY (game_session_id) REFERENCES game_sessions (id) ON DELETE CASCADE,
    CONSTRAINT fk_rounds_category FOREIGN KEY (category_id) REFERENCES categories (id),
    CONSTRAINT fk_rounds_question FOREIGN KEY (question_id) REFERENCES questions (id),
    CONSTRAINT fk_rounds_option FOREIGN KEY (selected_option_id) REFERENCES question_options (id),
    CONSTRAINT uk_rounds_session_number UNIQUE (game_session_id, round_number)
);

CREATE INDEX idx_rounds_session ON game_rounds (game_session_id);
